"""Shared writing standards for candidate-facing application materials."""

NATURAL_APPLICATION_VOICE = """- Write in a natural, clear, conversational voice that sounds like a smart, articulate college student and early-career professional.
- Keep the writing professional and warm, not stiff, salesy, academic, or overly polished.
- Use plain language, specific facts, and logical transitions. Avoid dense jargon, corporate filler, and sentences that sound assembled from keywords.
- Develop each point enough to be clear, but do not repeat evidence or pad the document.
- Be confident without exaggerating equivalence between transferable experience and the target role.
- Do not use artificial bridges such as maps directly, those settings, these experiences demonstrate, or solves the same problem."""


RESUME_VOICE = """- Resume writing should be concise and natural, with clear action verbs and no first-person pronouns.
- Skill categories must read like useful professional groupings, not copied job-ad fragments.
- Omit basic traits such as spelling, grammar, punctuation, attendance, willingness, and professionalism from the skills section unless they are a specialized requirement backed by evidence."""
